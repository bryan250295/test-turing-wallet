import { readFile, mkdir, writeFile } from 'node:fs/promises';
import { readFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { dirname, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import solc from 'solc';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const configurable = process.argv.includes('--configurable');
const redemption = process.argv.includes('--redemption');
const contractName = redemption ? 'LearningRedemptionEscrow' : configurable ? 'BridgeWrappedFT' : 'LearningWrappedFT';
const sourceName = `contracts/${contractName}.sol`;
const dependencyRoot = resolve(root, 'node_modules/@openzeppelin/contracts');
const artifactPath = resolve(root, `artifacts/${contractName}.json`);
const serverArtifactPath = resolve(root, `../shared/src/contracts/${redemption ? 'learningRedemptionEscrow' : configurable ? 'bridgeWrappedFT' : 'learningWrappedFT'}.ts`);

if (!solc.version().startsWith('0.8.30+')) throw new Error('Install the pinned Solidity compiler 0.8.30.');
const openzeppelin = JSON.parse(await readFile(resolve(dependencyRoot, 'package.json'), 'utf8'));
if (openzeppelin.version !== '5.4.0') throw new Error('Install the pinned OpenZeppelin Contracts 5.4.0.');

const input = {
    language: 'Solidity',
    sources: { [sourceName]: { content: await readFile(resolve(root, sourceName), 'utf8') } },
    settings: {
        // HyperEVM documents Cancun support. Do not use the compiler's newer default.
        evmVersion: 'cancun',
        optimizer: { enabled: true, runs: 200 },
        outputSelection: { '*': { '*': ['abi', 'evm.bytecode.object', 'evm.deployedBytecode.object', 'evm.deployedBytecode.immutableReferences', 'metadata'] } },
    },
};

const sources = { ...input.sources };
function readImport(path) {
    if (!path.startsWith('@openzeppelin/contracts/')) return { error: `Unsupported import: ${path}` };
    const resolved = resolve(root, 'node_modules', path);
    if (!resolved.startsWith(`${dependencyRoot}${sep}`)) return { error: `Import outside dependency: ${path}` };
    try {
        const content = readFileSync(resolved, 'utf8');
        sources[path] = { content };
        return { contents: content };
    } catch {
        return { error: `Cannot read import: ${path}` };
    }
}

const output = JSON.parse(solc.compile(JSON.stringify(input), { import: readImport }));
for (const diagnostic of output.errors ?? []) {
    console.error(diagnostic.formattedMessage);
}
if ((output.errors ?? []).some((entry) => entry.severity === 'error')) {
    throw new Error('Contract compilation failed; no new artifact was written.');
}

const compiled = output.contracts?.[sourceName]?.[contractName];
if (!compiled?.evm?.bytecode?.object || !compiled?.evm?.deployedBytecode?.object) {
    throw new Error('Compiler did not produce deployable bytecode.');
}
const deployedByteLength = compiled.evm.deployedBytecode.object.length / 2;
if (deployedByteLength > 24_576) throw new Error('Contract exceeds the EVM deployed code size limit.');

const buildInput = { ...input, sources };
const artifact = {
    contractName,
    sourceName,
    compilerVersion: solc.version(),
    openzeppelinVersion: openzeppelin.version,
    targetChainId: 998,
    buildInputSha256: createHash('sha256').update(JSON.stringify(buildInput)).digest('hex'),
    settings: input.settings,
    abi: compiled.abi,
    bytecode: `0x${compiled.evm.bytecode.object}`,
    deployedBytecode: `0x${compiled.evm.deployedBytecode.object}`,
    metadata: JSON.parse(compiled.metadata),
    buildInput,
};
await mkdir(dirname(artifactPath), { recursive: true });
await writeFile(artifactPath, `${JSON.stringify(artifact, null, 2)}\n`);
// Ship only deployment inputs to NestJS. This generated module is committed so
// Docker can build the backend without installing a second Solidity compiler.
const deployment = {
    contractName,
    compilerVersion: artifact.compilerVersion,
    targetChainId: artifact.targetChainId,
    buildInputSha256: artifact.buildInputSha256,
    sourceSha256: createHash('sha256').update(input.sources[sourceName].content).digest('hex'),
    abi: artifact.abi.filter((entry) => entry.type === 'constructor'),
    bytecode: artifact.bytecode,
};
const runtime = {
    bytecode: artifact.deployedBytecode,
    immutableReferences: Object.values(compiled.evm.deployedBytecode.immutableReferences ?? {}).flat(),
};
if (runtime.immutableReferences.length < 2) throw new Error('Compiler did not produce the source FT immutable reference locations.');
await mkdir(dirname(serverArtifactPath), { recursive: true });
const prefix = redemption ? 'LEARNING_REDEMPTION_ESCROW' : configurable ? 'BRIDGE_WRAPPED_FT' : 'LEARNING_WRAPPED_FT';
await writeFile(serverArtifactPath, `// Generated by wallet/scripts/compileBridgeContract.mjs. Do not edit by hand.\nexport const ${prefix}_BUILD = ${JSON.stringify(deployment, null, '\t')} as const;\nexport const ${prefix}_RUNTIME = ${JSON.stringify(runtime, null, '\t')} as const;\n`);
console.log(`Compiled ${contractName} (${deployedByteLength} runtime bytes) for Cancun / HyperEVM Testnet 998.`);
console.log(`Artifact: artifacts/${contractName}.json. No deployment or transaction was submitted.`);
